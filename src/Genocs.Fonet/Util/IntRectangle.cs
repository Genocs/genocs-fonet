namespace Fonet.Util
{
    public struct IntRectangle
    {
        public int X;
        public int Y;
        public int Width;
        public int Height;

        public IntRectangle(int x, int y, int width, int height)
        {
            X = x;
            Y = y;
            Width = width;
            Height = height;
        }
    }
}